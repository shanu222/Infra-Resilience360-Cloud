/**
 * District / city names per province for Design Toolkit, Apply Region, Retrofit location, and
 * `districtProvinceLookup`. Names are English labels commonly used in Pakistan admin maps.
 * First entry per province is the default when the user switches province.
 */

function provinceCities(primary: string, districts: readonly string[]): string[] {
  const all = new Set(districts.map((s) => s.trim()).filter(Boolean))
  all.add(primary)
  const rest = [...all].filter((c) => c !== primary).sort((a, b) => a.localeCompare(b))
  return [primary, ...rest]
}

