export function resolveDisaster(disaster: Disaster, lang: AppLanguage): Disaster {
  if (lang === 'en') return disaster
  const overlay = ur[disaster.id]
  if (!overlay) return disaster
  return { ...disaster, ...overlay }
}

export function getLocalizedDisasters(lang: AppLanguage): Disaster[] {
  return DISASTER_DASHBOARD_DISASTERS.map((d) => resolveDisaster(d, lang))
}
